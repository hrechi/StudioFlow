"use client";

import { Check, Loader2, RefreshCw, Sparkles } from "lucide-react";
import { useRef, useState, useTransition } from "react";
import type { UseFormReturn } from "react-hook-form";
import { toast } from "sonner";
import { AIPanel } from "@/components/shared/ai-panel";
import { Button } from "@/components/ui/button";
import {
  Select,
  SelectContent,
  SelectItem,
  SelectTrigger,
  SelectValue,
} from "@/components/ui/select";
import { Textarea } from "@/components/ui/textarea";
import { LANGUES_SUGGESTION } from "../catalogue.schemas";
import { suggestPackTextAction } from "../catalogue.actions";
import type { PackInput } from "../catalogue.schemas";
import type { LangueSuggestion, PackSuggestionDTO } from "../catalogue.types";

const OBJECT_ID = /^[a-f\d]{24}$/i;

const LANGUE_LABELS: Record<LangueSuggestion, string> = {
  en: "🇬🇧 English",
  fr: "🇫🇷 Français",
  ar: "🇹🇳 العربية",
};

/**
 * Name and description ideas for the pack being edited.
 * The AI (Groq) or the template fallback proposes from the services, duration and options
 * already in the form. The admin picks a language, clicks "Suggest", then clicks "Use" to
 * copy into the field. Nothing is saved here.
 */
export function PackAiSuggestions({
  form,
  packId,
}: {
  form: UseFormReturn<PackInput>;
  packId?: string;
}) {
  const [langue, setLangue] = useState<LangueSuggestion>("en");
  const [remarque, setRemarque] = useState("");
  const [result, setResult] = useState<PackSuggestionDTO | null>(null);
  const [pending, startTransition] = useTransition();
  // Everything already shown in the current language, so "Suggest more" brings something new.
  const shownNames = useRef<string[]>([]);
  const shownDescriptions = useRef<string[]>([]);

  const typeId = form.watch("typeEvenementId");
  const currentName = form.watch("nom");
  const currentDescription = form.watch("description");

  /** Changing the language resets the panel: new suggestions will be in the new language. */
  const handleLangueChange = (val: string) => {
    setLangue(val as LangueSuggestion);
    setResult(null);
    shownNames.current = [];
    shownDescriptions.current = [];
  };

  const suggest = () => {
    const v = form.getValues();
    startTransition(async () => {
      const response = await suggestPackTextAction({
        typeEvenementId: v.typeEvenementId,
        packId,
        langue,
        prestations: v.prestations
          .filter((l) => OBJECT_ID.test(l.prestationId))
          .map((l) => ({
            prestationId: l.prestationId,
            quantite: Number.isInteger(l.quantite) && l.quantite >= 1 ? l.quantite : 1,
          })),
        prix: Number.isFinite(v.prix) && v.prix >= 0 ? v.prix : 0,
        dureeEstimeeMinutes:
          Number.isInteger(v.dureeEstimeeMinutes) && v.dureeEstimeeMinutes >= 0
            ? v.dureeEstimeeMinutes
            : 0,
        options: v.options.map((o) => o.nom.trim()).filter(Boolean),
        nomsDejaProposes: shownNames.current.slice(-12),
        descriptionsDejaProposees: shownDescriptions.current.slice(-4),
        ...(remarque.trim() ? { remarque: remarque.trim() } : {}),
      });
      if (!response.ok) {
        toast.error(response.error);
        return;
      }
      const { noms, descriptions } = response.data;
      if (noms.length === 0 && descriptions.length === 0) {
        toast.info("No new idea this time. Change the services or the duration and try again.");
        return;
      }
      shownNames.current.push(...noms);
      shownDescriptions.current.push(...descriptions.map((d) => d.slice(0, 300)));
      setResult(response.data);
      if (response.data.source === "MODELE") {
        toast.info("The AI is unavailable: showing template suggestions.");
      }
    });
  };

  const apply = (field: "nom" | "description", value: string) =>
    form.setValue(field, value, { shouldDirty: true, shouldValidate: true });

  // Arabic text needs RTL direction
  const isRtl = result?.langue === "ar";

  return (
    <AIPanel
      title="Name & description ideas"
      description={'Written from the event type, services, duration and options above. Nothing is changed until you click \u201cUse\u201d, and you still save the pack yourself.'}
      footer={
        result ? (
          <p className="text-xs text-muted-foreground">
            {result.source === "IA"
              ? "Generated by AI — check the wording before publishing. Prices are never included: they come from the price field."
              : "Template suggestions built from your pack data (AI unavailable)."}
          </p>
        ) : undefined
      }
    >
      <div className="space-y-4">
        {/* Language selector + trigger button on the same row */}
        <div className="flex flex-wrap items-center gap-2">
          <Select value={langue} onValueChange={handleLangueChange}>
            <SelectTrigger className="h-8 w-36 bg-card text-sm">
              <SelectValue />
            </SelectTrigger>
            <SelectContent>
              {LANGUES_SUGGESTION.map((l) => (
                <SelectItem key={l} value={l}>
                  {LANGUE_LABELS[l]}
                </SelectItem>
              ))}
            </SelectContent>
          </Select>

          <Button
            type="button"
            size="sm"
            variant="ai-soft"
            onClick={suggest}
            disabled={pending || !typeId}
          >
            {pending ? (
              <Loader2 className="animate-spin" aria-hidden />
            ) : result ? (
              <RefreshCw aria-hidden />
            ) : (
              <Sparkles aria-hidden />
            )}
            {result ? "Suggest more" : "Suggest a name and description"}
          </Button>
        </div>

        {!typeId && (
          <p className="text-xs text-muted-foreground">Choose an event type first.</p>
        )}

        {/* Optional note: tone, angle, target audience, keywords… */}
        <div className="space-y-1">
          <label htmlFor="pack-ai-remarque" className="text-xs font-medium text-muted-foreground">
            Note for the AI{" "}
            <span className="font-normal">(optional — tone, angle, keywords…)</span>
          </label>
          <Textarea
            id="pack-ai-remarque"
            rows={2}
            maxLength={300}
            placeholder='e.g. "Keep it romantic and poetic" or "Target young couples"'
            className="resize-none bg-card text-sm"
            value={remarque}
            onChange={(e) => setRemarque(e.target.value)}
          />
          {remarque.trim().length > 0 && (
            <p className="text-right text-xs text-muted-foreground">
              {remarque.trim().length}/300
            </p>
          )}
        </div>

        {result && result.noms.length > 0 && (
          <div className="space-y-2">
            <p className="text-xs font-medium text-muted-foreground">Names</p>
            <ul className="flex flex-wrap gap-2">
              {result.noms.map((nom) => {
                const applied = currentName?.trim() === nom;
                return (
                  <li key={nom}>
                    <Button
                      type="button"
                      size="sm"
                      variant="outline"
                      className="h-8 rounded-full bg-card"
                      dir={isRtl ? "rtl" : undefined}
                      onClick={() => apply("nom", nom)}
                      aria-pressed={applied}
                    >
                      {applied && <Check aria-hidden />}
                      {nom}
                    </Button>
                  </li>
                );
              })}
            </ul>
          </div>
        )}

        {result && result.descriptions.length > 0 && (
          <div className="space-y-2">
            <p className="text-xs font-medium text-muted-foreground">Descriptions</p>
            <ul className="space-y-2">
              {result.descriptions.map((texte) => {
                const applied = currentDescription?.trim() === texte;
                const replaces = !!currentDescription?.trim() && !applied;
                return (
                  <li
                    key={texte}
                    className="flex flex-col gap-2 rounded-lg border bg-card p-3 sm:flex-row sm:items-start sm:justify-between"
                  >
                    <p
                      className="text-sm whitespace-pre-line text-foreground"
                      dir={isRtl ? "rtl" : undefined}
                    >
                      {texte}
                    </p>
                    <Button
                      type="button"
                      size="sm"
                      variant="outline"
                      className="shrink-0"
                      onClick={() => apply("description", texte)}
                      disabled={applied}
                    >
                      {applied ? <Check aria-hidden /> : null}
                      {applied ? "Used" : replaces ? "Replace description" : "Use"}
                    </Button>
                  </li>
                );
              })}
            </ul>
          </div>
        )}
      </div>
    </AIPanel>
  );
}
