import "server-only";
import { createHmac, timingSafeEqual } from "node:crypto";
import { findSharedGalerie } from "./galerie.service";
import type { Galerie } from "./galerie.types";

/**
 * Guest access to a shared gallery (/g/<lienAcces>): once the password is
 * checked, an httpOnly cookie remembers it for that gallery. The cookie is an
 * HMAC of the token + the password hash, so it can't be forged and stops
 * working as soon as the studio changes or removes the password.
 */

const COOKIE_PREFIX = "sf_galerie_";
const COOKIE_MAX_AGE = 30 * 24 * 60 * 60; // seconds

/** A lienAcces token (base64url, generated by createGalerie). */
export const TOKEN_PATTERN = /^[A-Za-z0-9_-]{8,64}$/;

export function guestCookieName(token: string): string {
  return `${COOKIE_PREFIX}${token}`;
}

function secret(): string {
  const value = process.env.AUTH_SECRET;
  if (!value) throw new Error("AUTH_SECRET is not set.");
  return value;
}

export function signGuestAccess(token: string, passwordHash: string): string {
  return createHmac("sha256", secret()).update(`${token}:${passwordHash}`).digest("base64url");
}

export function isGuestAccessValid(
  token: string,
  passwordHash: string,
  cookieValue: string | undefined,
): boolean {
  if (!cookieValue) return false;
  const expected = Buffer.from(signGuestAccess(token, passwordHash));
  const actual = Buffer.from(cookieValue);
  return expected.length === actual.length && timingSafeEqual(expected, actual);
}

/** Cookie lifetime: until the gallery expires, 30 days at most. */
export function guestCookieMaxAge(dateExpiration: string): number {
  const untilExpiry = Math.floor((Date.parse(dateExpiration) - Date.now()) / 1000);
  return Math.max(60, Math.min(COOKIE_MAX_AGE, untilExpiry));
}

/** Accepts a full link (https://…/g/<token>), a path (/g/<token>) or the bare code. */
export function extractToken(input: string): string | null {
  const value = input.trim();
  const match = value.match(/\/g\/([A-Za-z0-9_-]+)/);
  const token = match ? match[1] : value;
  return TOKEN_PATTERN.test(token) ? token : null;
}

export type GuestAccess =
  | { status: "unavailable" }
  | { status: "locked"; galerie: Galerie }
  | { status: "open"; galerie: Galerie };

/** Used by the /g/[token] page and the guest photo route. */
export async function getGuestAccess(
  token: string,
  cookieValue: string | undefined,
): Promise<GuestAccess> {
  if (!TOKEN_PATTERN.test(token)) return { status: "unavailable" };
  const shared = await findSharedGalerie(token);
  if (shared.status !== "ok") return { status: "unavailable" };
  const open = !shared.passwordHash || isGuestAccessValid(token, shared.passwordHash, cookieValue);
  return { status: open ? "open" : "locked", galerie: shared.galerie };
}
